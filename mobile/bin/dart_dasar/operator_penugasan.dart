void main() {
  int a = 10; // 10
  print(a);

  a += 7; // 10 + 7 = 17
  print(a);

  a -= 6; // 17 - 6 = 11
  print(a);

  a *= 5; // 11 * 5 = 55
  print(a);

  a ~/= 4; // 55 ~/ 4 = 13
  print(a);

  a %= 3; // 13 / 3 = 4, sisa 1 (dibaca 13 modulo 3, krn yg dicari sisa hasil pembagian)
  print(a);
}
